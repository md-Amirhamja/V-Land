// Reads node names from public/models/*.glb (JSON chunk only, no three.js) + src/names-bn.js
// and writes supabase/migrations/003_geo_units_seed.sql  (8 divisions, 64 districts, 546 areas).
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = path.resolve(import.meta.dirname, '..');
const { default: BN_LIST, EN_FIX } = await import(pathToFileURL(path.join(root, 'src/names-bn.js')).href);

const norm = (s) => s.toLowerCase().replace(/[^a-z]/g, '');
const BN = {};
BN_LIST.forEach(([bn, ...en]) => en.forEach((e) => (BN[norm(e)] = bn)));

const pretty = (s) => s.replace(/_/g, ' ').replace(/\s+/g, ' ').trim();
const clean = (s) => pretty(s).replace(/\s+\d+$/, '');
const nameEn = (s) => { const c = clean(s); return (EN_FIX && EN_FIX[c]) || c; };
const nameBn = (s) => { const c = clean(s); return BN[norm(c)] || BN[norm(nameEn(s))] || null; };

function glbNodeNames(file) {
  const b = fs.readFileSync(file);
  const len = b.readUInt32LE(12);
  return JSON.parse(b.subarray(20, 20 + len).toString('utf8')).nodes.map((n) => n.name).filter(Boolean);
}
const q = (s) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`);

const levels = [['division', 'divisions.glb'], ['district', 'districts.glb'], ['area', 'areas.glb']];
const out = ['-- 003_geo_units_seed.sql  (generated by scripts/gen-geo-units.mjs - do not edit by hand)',
  '-- Run after 001_core.sql. Safe to re-run: existing keys are skipped.', ''];
const missing = [];
let total = 0;

levels.forEach(([level, file], i) => {
  const names = glbNodeNames(path.join(root, 'public/models', file)).sort();
  out.push(`-- ${level}s (${names.length})`);
  for (const key of names) {
    const parts = key.split('__');
    const last = parts[parts.length - 1];
    const bn = nameBn(last);
    if (!bn) missing.push(key);
    const parentKey = i === 0 ? null : parts.slice(0, -1).join('__');
    const parent = parentKey ? `(select id from public.geo_units where glb_key = ${q(parentKey)})` : 'null';
    out.push(`insert into public.geo_units (level, parent_id, name_en, name_bn, glb_key) values (${q(level)}, ${parent}, ${q(nameEn(last))}, ${q(bn || nameEn(last))}, ${q(key)}) on conflict (glb_key) do nothing;`);
    total++;
  }
  out.push('');
});
out.push("select level, count(*) from public.geo_units group by level order by 1;  -- expect: area 546, district 64, division 8");
fs.writeFileSync(path.join(root, 'supabase/migrations/003_geo_units_seed.sql'), out.join('\n') + '\n');
console.log(`wrote ${total} rows; ${missing.length} without a Bangla name`, missing.slice(0, 10));
